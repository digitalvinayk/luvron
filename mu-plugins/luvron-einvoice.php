/**
 * Plugin Name: Luvron — GST E-Invoice (IRN/QR)
 * Description: Generates IRN and QR code for B2B invoices via the IRP (Invoice Registration Portal).
 *              Supports two modes:
 *                1. Manual — admin enters IRN/QR after generating from external tool (zero-cost)
 *                2. API — auto-generate via ClearTax/Cygnet/GSTHero IRP API (₹15-25k/yr)
 *              Mandatory under GST law if turnover ≥ ₹5 cr.
 * Version: 1.0.0
 */

